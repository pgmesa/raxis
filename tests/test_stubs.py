import ast
from pathlib import Path

import pytest
import raxis


STUB = Path(raxis.__file__).parent / '_C' / '__init__.pyi'


def tensor_methods():
    tree = ast.parse(STUB.read_text())
    tensor = next(node for node in tree.body if isinstance(node, ast.ClassDef) and node.name == 'Tensor')
    return [node for node in tensor.body if isinstance(node, ast.FunctionDef)]


@pytest.mark.skipif(not STUB.exists(), reason="stubs are generated by scripts/build_libraxis.py")
def test_tensor_methods_have_a_return_type():
    # A method without one breaks autocompletion after it (x.view(6). shows
    # nothing). raxis/__init__.py replaces some methods with Python wrappers,
    # whose signature pybind11-stubgen cannot read: generate_pyi.py unwraps
    # them or writes their stubs by hand
    assert [m.name for m in tensor_methods() if m.returns is None] == []
    assert [m.name for m in tensor_methods() if m.args.vararg and m.args.vararg.annotation is None] == []
